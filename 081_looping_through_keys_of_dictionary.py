countries = {
    "IN": "India",
    "CA": "Canada",
    "US": "United States",
    "MX": "Mexico",
    "DE": "Germany",
    "UK": "United Kingdom",
    "AU": "Australia",
    "NZ": "New Zealand",
}

# Print all keys in the dictionary
for key in countries:
    print(key, end=" ")

print()  # Add a newline for better readability

# Alternatively, using the .keys() method
for key in countries.keys():
    print(key, end=" ")
